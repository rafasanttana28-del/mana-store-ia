create table if not exists public.opportunities (
  id bigint generated by default as identity primary key,
  niche text not null,
  market text not null check (market in ('Brazil', 'International')),
  product_idea text not null default '',
  commercial_potential text not null default 'unproven'
    check (commercial_potential in ('low', 'medium', 'high', 'unproven')),
  evidence_confidence text not null default 'low'
    check (evidence_confidence in ('low', 'medium', 'high')),
  rationale text not null default '',
  risks jsonb not null default '[]'::jsonb,
  source_urls jsonb not null default '[]'::jsonb,
  checked_at timestamptz not null default now(),
  status text not null default 'research_only',
  created_at timestamptz not null default now()
);

create index if not exists opportunities_checked_at_idx
  on public.opportunities (checked_at desc);
create index if not exists opportunities_market_idx
  on public.opportunities (market);

alter table public.opportunities enable row level security;
-- No public policies are created. Access is server-side only via service role.
